// Shared "screening" control every scenario runs, regardless of outcome —
// makes the injection defense visible even when nothing is actually flagged.
function sourceScreeningControl(flagged: boolean, matchedPhrase?: string): ControlResult {
  return {
    controlId: "source_screening",
    label: "Embedded-instruction screening",
    status: flagged ? "warning" : "passed",
    severity: flagged ? "high" : "low",
    reason: flagged
      ? `Instruction-shaped content detected in the invoice notes ("${matchedPhrase}"). Treated as untrusted text — ignored by every downstream control and never used to change a decision, a status, or supplier data.`
      : "No instruction-shaped content detected in extracted text fields.",
    evidenceReferences: flagged ? ["notes"] : [],
    blocking: false,
  };
}

